import { test, expect } from "vitest";

import { ScoreCalculator } from "../index.ts";

test("handに和了牌を含む標準入力はseat_windとround_windの2翻40符・親ロン3900点を返す", () => {
  const input = {
    hand: ["1m", "2m", "3m", "4p", "5p", "6p", "7s", "8s", "9s", "ton", "ton", "ton", "5m", "5m"],
    melds: [],
    winTile: "5m",
    winType: "ron",
    seatWind: "ton",
    roundWind: "ton",
    dora: [],
    uraDora: [],
    riichi: "none",
    ippatsu: false,
    situational: [],
  };

  expect(ScoreCalculator.calculateFromJson(JSON.stringify(input))).toStrictEqual({
    valid: true,
    yaku: [
      { name: "seat_wind", han: 1 },
      { name: "round_wind", han: 1 },
    ],
    han: 2,
    fu: 40,
    score: { total: 3900, payments: [{ from: "discarder", amount: 3900 }] },
  });
});
